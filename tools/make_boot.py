#!/usr/bin/env python3
"""make_boot.py - GAME.BIN: the engine's four images, packed, and the
loader that unpacks them (src/boot.asm, CLAUDE.md 4).

    build/engine.bin   what src/main.asm assembles: core, HIGH, SOUND, TOP
    build/game.sym     ... and where each of them goes
 -> build/boot_*.zx0   one ZX0 stream an image
 -> build/boot.inc     the addresses the loader needs, out of game.sym
 -> build/game.bin     src/boot.asm around the four - what goes on the
                       disc as GAME.BIN

Runs on every build, --relink included: it reads only what RASM has
just written, so there is nothing it could take from a stale asset.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
BUILD = os.path.join(ROOT, "build")

# what the loader takes from the engine's own symbols
WANT = ("CORE_ADDR", "CORE_SIZE", "CORE_ENTRY", "HIGH_ADDR", "HIGH_SIZE",
        "HIGH_IMAGE", "SOUND_ADDR", "SOUND_SIZE", "SOUND_IMAGE",
        "TOP_ADDR", "TOP_SIZE", "TOP_IMAGE",
        "BOOT_ADDR", "STACK_TOP", "GA_PORT", "RMR_MODE0", "RAM_CFG_BASE")


def symbols():
    sym = {}
    for line in open(os.path.join(BUILD, "game.sym")):
        m = re.match(r"^(\S+) #([0-9A-F]+) ", line)
        if m:
            sym[m.group(1)] = int(m.group(2), 16)
    return sym


def pack(name, data):
    raw = os.path.join(BUILD, f"boot_{name}.bin")
    out = os.path.join(BUILD, f"boot_{name}.zx0")
    asm = os.path.join(BUILD, "_boot_pack.asm")
    open(raw, "wb").write(data)
    with open(asm, "w") as f:
        f.write(f'        org 0\n        LZX0\n        incbin "{raw}"\n'
                f'        LZCLOSE\n')
    r = subprocess.run(["rasm", asm, "-amper", "-ob", out],
                       capture_output=True, text=True)
    os.remove(asm)
    if r.returncode or not os.path.exists(out):
        raise SystemExit(f"packing {name} failed:\n{r.stdout}{r.stderr}")
    return os.path.getsize(out)


def main():
    sym = symbols()
    missing = [w for w in WANT if w not in sym]
    if missing:
        raise SystemExit(f"game.sym has no {', '.join(missing)}")
    engine = open(os.path.join(BUILD, "engine.bin"), "rb").read()
    base = sym["BOOT_ADDR"]                  # where RASM's output starts
    images = {}
    for name, image, size in (("core", "BOOT_ADDR", "CORE_SIZE"),
                              ("high", "HIGH_IMAGE", "HIGH_SIZE"),
                              ("sound", "SOUND_IMAGE", "SOUND_SIZE"),
                              ("top", "TOP_IMAGE", "TOP_SIZE")):
        at = sym[image] - base
        images[name] = engine[at:at + sym[size]]
        assert len(images[name]) == sym[size], name
    # the four are the WHOLE file, back to back, or something in it is
    # being left behind
    assert sum(len(b) for b in images.values()) == len(engine), \
        (len(engine), {k: len(v) for k, v in images.items()})
    packed = {n: pack(n, b) for n, b in images.items()}
    with open(os.path.join(BUILD, "boot.inc"), "w") as f:
        f.write("; GENERATED by tools/make_boot.py out of game.sym\n")
        for w in WANT:
            f.write(f"{w:<16}equ &{sym[w]:04X}\n")
    r = subprocess.run(["rasm", os.path.join(ROOT, "src", "boot.asm"),
                        "-I", os.path.join(ROOT, "src"), "-I", BUILD,
                        "-amper", "-ob", os.path.join(BUILD, "game.bin"),
                        "-s", "-sa", "-os", os.path.join(BUILD, "boot.sym")],
                       capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(f"src/boot.asm:\n{r.stdout}{r.stderr}")
    game = os.path.getsize(os.path.join(BUILD, "game.bin"))
    for n in images:
        print(f"  {n:<6} {len(images[n]):6} -> {packed[n]:6} packed")
    print(f"-> game.bin  {len(engine)} bytes of engine in {game} "
          f"({(game + 128 + 1023) // 1024} AMSDOS blocks with its header)")


if __name__ == "__main__":
    main()
